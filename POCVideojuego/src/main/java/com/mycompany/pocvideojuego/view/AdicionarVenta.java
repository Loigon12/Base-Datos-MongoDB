    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
       // Obtener valores de los campos (ajustado a Venta)
    String codigoVentaStr = txtCodigoVenta.getText().trim(); // Reutilizado: código de la venta
    String cliente = txtCliente.getText().trim();                 // Nombre del cliente
    String venta = txtFecha.getText().trim();                 // Nombre del cliente
    String totalStr = txtTotalVenta1.getText().trim();     // Total de la venta
    

    // Validaciones básicas
    if (codigoVentaStr.isEmpty() || cliente.isEmpty() || totalStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, 
            "Campos obligatorios:\n• Código Venta\n• Cliente\n• Total Venta\n• Código Videojuego", 
            "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    int codigoVenta;
    double totalVenta;

    try {
        codigoVenta = Integer.parseInt(codigoVentaStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El código de venta debe ser un número entero.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        totalVenta = Double.parseDouble(totalStr);
        if (totalVenta <= 0) {
            JOptionPane.showMessageDialog(this, "El total de la venta debe ser mayor a 0.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El total de la venta debe ser un número válido (ej. 59.99).", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    

    // Crear objeto Venta
    Venta nuevaVenta = new Venta();
    nuevaVenta.setCodigoVenta(codigoVenta);   // ID de la venta
    nuevaVenta.setCliente(cliente);
    nuevaVenta.setTotalVenta(totalVenta);
   
    // Guardar usando el servicio
    boolean exito = ServiciosVenta.agregarVenta(nuevaVenta);

    if (exito) {
        JOptionPane.showMessageDialog(this, 
            "¡Venta #" + codigoVenta + " registrada con éxito!\nCliente: " + cliente, 
            "Éxito", JOptionPane.INFORMATION_MESSAGE);
        // Limpiar campos
        txtCodigoVenta.setText(""); // ← código venta
        txtCliente.setText("");   
        txtFecha.setText("");   // ← cliente
        txtTotalVenta1.setText(""); // ← total
    } else {
        JOptionPane.showMessageDialog(this, 
            "Error al registrar la venta.\n" +
            "• ¿Ya existe una venta con ese código?\n" +
            "• ¿Está corriendo MongoDB?", 
            "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnAdicionarActionPerformed


