        /**
         * Muestra en lblSumatoria la sumatoria total de precios (todos los registros).
         */
        private void cargarSumatoria() {
            double total = ServiciosPublisher.sumatoriaPreciosSuscripcion(false); // false => todos (no filtra por estado)
            lblSumatoria.setText(String.format("Sumatoria total de precios: %.2f", total));
        }

        /**
         * Calcula y muestra los registros con precio > límite ingresado por el usuario.
         * Actualiza tablaResultados y lblInfo; además indica si >=50% supera el límite.
         */
        private void calcularPorLimite() {
            String texto = txtLimite.getText().trim();
            if (texto.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Ingresa una cantidad límite.", "Atención", JOptionPane.WARNING_MESSAGE);
                return;
            }

            double limite;
            try {
                limite = Double.parseDouble(texto);
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Límite inválido. Ingresa un número válido.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Obtener todos los videojuegos y filtrar
            List<Publisher> lista = ServiciosPublisher.listarPublisher();
            DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{"CódigoPublisher", "Nombre", "Region", "Precio Suscripción", "En servicio"}, 0
            ) {
                @Override
                public boolean isCellEditable(int row, int column) {
                    return false;
                }
            };

            int contador = 0;
            for (Publisher pb : lista) {
                if (pb.getPrecioSuscripcion()> limite) {
                    contador++;
                    modelo.addRow(new Object[]{
                        pb.getCodigoPublisher(),
                        pb.getNombre(),
                        pb.getRegion(),
                        pb.getPrecioSuscripcion(),
                        pb.getEnServicio()
                    });
                }
            }

            tablaResultados.setModel(modelo);

            // Información de resumen
            lblInfo.setText(String.format("%d registros con precio > %.2f (de %d registros totales)",
                contador, limite, lista.size()));

            // Mostrar si el 50% o más supera el límite
            boolean mas50 = ServiciosPublisher.masDel50PorcientoSuperaSuscripcion(limite);
            if (mas50) {
                JOptionPane.showMessageDialog(this, "El 50% o más de los registros superan el límite.", "Resultado", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Menos del 50% de los registros superan el límite.", "Resultado", JOptionPane.INFORMATION_MESSAGE);
            }
        }

