    private void btnActualizarVActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarVActionPerformed
        String codigoStr = jtrespuestacodigo.getText().trim();
if (codigoStr.isEmpty() || "________".equals(codigoStr)) {
    JOptionPane.showMessageDialog(this, "Primero debes buscar un videojuego para actualizar.");
    return;
}

int codigoSerie;
try {
    codigoSerie = Integer.parseInt(codigoStr);
} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this, "Código de videojuego inválido.");
    return;
}

// Buscar el videojuego real (no depender solo de los campos)
Videojuego vj = ServiciosVideojuego.buscarVideojuego(codigoSerie);
if (vj == null) {
    JOptionPane.showMessageDialog(this, "No se encontró el videojuego. Es posible que haya sido eliminado.");
    return;
}

// Actualizar nombre (solo si no está vacío)
String nombre = jtNombre.getText().trim();
if (!nombre.isEmpty()) {
    vj.setNombre(nombre);
}

// Actualizar estado (solo si no está vacío)
String estado = jtEstado.getText().trim();
if (!estado.isEmpty()) {
    vj.setEstado(estado);
}

// Actualizar precio (con validación)
String precioStr = jtPrecio.getText().trim();
if (!precioStr.isEmpty()) {
    try {
        double precio = Double.parseDouble(precioStr);
        if (precio < 0) {
            JOptionPane.showMessageDialog(this, "El precio no puede ser negativo.");
            return;
        }
        vj.setPrecio(precio);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Precio inválido. No se actualizará este campo.");
        return;
    }
}

// Actualizar código del publisher (clave para relación lógica y GUI)
String codPublisherStr = jtCodigoPublisher.getText().trim();
if (!codPublisherStr.isEmpty()) {
    try {
        int codigoPublisher = Integer.parseInt(codPublisherStr);
        if (codigoPublisher <= 0) {
            JOptionPane.showMessageDialog(this, "El código de publisher debe ser un número positivo.");
            return;
        }
        
        // ✅ Validar existencia del publisher (opcional pero recomendado)
        Publisher pb = ServiciosPublisher.buscarPublisher(codigoPublisher);
        if (pb == null) {
            int opcion = JOptionPane.showConfirmDialog(this,
                "⚠️ El Publisher con código " + codigoPublisher + " no existe.\n" +
                "¿Deseas asignarlo igual? (el videojuego podría quedar sin publisher válido)",
                "Publisher no encontrado",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);
            if (opcion != JOptionPane.YES_OPTION) {
                return;
            }
        }
        vj.setCodigoPublisher(codigoPublisher);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Código de publisher inválido.");
        return;
    }
}

// ✅ Ejecutar actualización
boolean ok = ServiciosVideojuego.actualizarVideojuego(vj);
if (ok) {
    JOptionPane.showMessageDialog(this, "✅ Videojuego actualizado correctamente.");
} else {
    JOptionPane.showMessageDialog(this, "❌ No se pudo actualizar el videojuego. Verifica los datos e inténtalo nuevamente.");
}
    }//GEN-LAST:event_btnActualizarVActionPerformed

