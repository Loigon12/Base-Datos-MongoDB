    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
            String texto = jTextField1.getText().trim();
    
    if (texto.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingresa un código o nombre para buscar.");
        return;
    }

    var resp = (Videojuego) null;

    // Intentar buscar por código
    try {
        int codigo = Integer.parseInt(texto);
        resp = serviciosvideojuego.buscarVideojuego(codigo);
    } catch (NumberFormatException e) {
        // No es número, buscar por nombre directamente en la lista
        for (Videojuego v : serviciosvideojuego.listarVideojuegos()) {
            if (v.getNombre().equalsIgnoreCase(texto)) {
                resp = v;
                break;
            }
        }
    }

    if (resp != null) {
    jtrespuestacodigo.setText(String.valueOf(resp.getCodigoSerie()));
    jtNombre.setText(resp.getNombre());
    jtEstado.setText(resp.getEstado());
    jtPrecio.setText(String.valueOf(resp.getPrecio()));
    
} else {
    jtrespuestacodigo.setText("");
   
    JOptionPane.showMessageDialog(this, "No se encontró el registro solicitado.");
}

        
//        JOptionPane.showMessageDialog(this, "nom: " + jTextField1.getText());
    }//GEN-LAST:event_btnBuscarActionPerformed

