    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        String codigoStr = jTextField2.getText().trim();
        if (codigoStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No hay código de Publisher para actualizar.");
            return;
        }

        int codigoPublisher;
        try {
            codigoPublisher = Integer.parseInt(codigoStr);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Código de Publisher inválido.");
            return;
        }

        Publisher pb = ServiciosPublisher.buscarPublisher(codigoPublisher);
        if (pb == null) {
            JOptionPane.showMessageDialog(this, "No se encontró el Publisher.");
            return;
        }

        String nombre = jTextField3.getText().trim();
        if (!nombre.isEmpty()) {
            pb.setNombre(nombre);
        }

        String region = jTextField4.getText().trim();
        if (!region.isEmpty()) {
            pb.setRegion(region);
        }

        String precioStr = jTextField5.getText().trim();
        if (!precioStr.isEmpty()) {
            precioStr = precioStr.replace("$", "").replace(",", ".").trim();
            try {
                double precio = Double.parseDouble(precioStr);
                pb.setPrecioSuscripcion(precio);
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Precio inválido. No se actualizará este campo.");
            }
        }

        boolean ok = ServiciosPublisher.actualizarPublisher(pb);
        if (ok) {
            JOptionPane.showMessageDialog(this, "Publisher actualizado correctamente.");
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo actualizar el Publisher. Verifica los datos.");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

