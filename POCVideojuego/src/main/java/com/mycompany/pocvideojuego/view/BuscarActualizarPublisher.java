    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
     String texto = jTextField1.getText().trim();

    if (texto.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingresa un código o nombre para buscar.");
        return;
    }

    Publisher publisherEncontrado = null;

    // Intentar buscar por código primero
    try {
        int codigo = Integer.parseInt(texto);
        publisherEncontrado = ServiciosPublisher.buscarPublisher(codigo);
    } catch (NumberFormatException e) {
        // No es número, buscar por nombre
        List<Publisher> publishers = ServiciosPublisher.listarPublisher();
        for (Publisher pb : publishers) {
            if (pb.getNombre().equalsIgnoreCase(texto)) {
                publisherEncontrado = pb;
                break;
            }
        }
    }

    if (publisherEncontrado == null) {
        JOptionPane.showMessageDialog(this, "No se encontró ningún Publisher con ese código o nombre.");
        
        // Limpiar los campos si no se encuentra nada
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
        jTextField5.setText("");
        return;
    }

    // ✅ Contar cuántos videojuegos están asociados a este publisher
    List<Videojuego> todosLosJuegos = ServiciosVideojuego.listarVideojuegos();
    int cantidadJuegos = 0;
    for (Videojuego v : todosLosJuegos) {
        if (v.getCodigoPublisher() == publisherEncontrado.getCodigoPublisher()) {
            cantidadJuegos++;
        }
    }

    // ✅ Mostrar información directamente en los JTextField
    jTextField2.setText(String.valueOf(publisherEncontrado.getCodigoPublisher()));  // Código
    jTextField3.setText(publisherEncontrado.getNombre());                           // Nombre
    jTextField4.setText(publisherEncontrado.getRegion());                           // Región
    jTextField5.setText("$" + String.format("%.2f", publisherEncontrado.getPrecioSuscripcion())); // Precio

    // (Opcional) mensaje de confirmación
    JOptionPane.showMessageDialog(this, 
        "Búsqueda realizada con éxito.\n" +
        "Este publisher tiene " + cantidadJuegos + " videojuegos asociados.");
    }//GEN-LAST:event_btnBuscarActionPerformed

