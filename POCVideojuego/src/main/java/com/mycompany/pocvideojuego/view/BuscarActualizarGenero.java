    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
       if (codigoPublisherBuscado == -1 || nombreOriginal == null) { 
     JOptionPane.showMessageDialog(this, "Realiza una búsqueda exitosa primero.");
     return;
    }

    // Usamos el ID de la búsqueda guardado
    Genero g = new Genero(); 
    
    // El ID Genero (jTextField2) y CodigoPub (jTextField5) no cambian, solo se reutilizan/validan
    try {
         g.setIdGenero(Integer.parseInt(jTextField2.getText().trim()));
    } catch (NumberFormatException e) {
         JOptionPane.showMessageDialog(this, "ID Genero no es válido.");
         return;
    }
    try {
        // Asumiendo que CodigoPublisher es INT, lo obtenemos del campo (o mejor, del estado)
        // Usaremos el estado guardado, pero validamos el campo por si acaso:
        g.setCodigoPublisher(Integer.parseInt(jTextField5.getText().trim()));
    } catch (NumberFormatException e) {
         JOptionPane.showMessageDialog(this, "Código Publisher no es válido.");
         return;
    }
    
    // 2. Obtener y actualizar el Nombre
    String nombre = jTextField3.getText().trim();
    if (nombre.isEmpty()) { 
        JOptionPane.showMessageDialog(this, "El nombre no puede estar vacío.");
        return; 
    }
    g.setNombre(nombre); 

    // 3. Obtener y actualizar la Calificación (Validar INT)
    String calificacionStr = jTextField4.getText().trim();
    if (calificacionStr.isEmpty()) { 
        JOptionPane.showMessageDialog(this, "La calificación no puede estar vacía.");
        return;
    }
    try {
        int calificacion = Integer.parseInt(calificacionStr);
        // Opcional: Validar que 1 <= calificacion <= 10
        if (calificacion < 1 || calificacion > 10) {
             JOptionPane.showMessageDialog(this, "La calificación debe estar entre 1 y 10.");
             return;
        }
        g.setCalificacion(calificacion); 
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Calificación inválida (debe ser un número entero).");
        return;
    }

    // 4. 🚨 CRÍTICO: Llamar al servicio de actualización con los 3 parámetros
    boolean ok = ServiciosGenero.actualizarGenero(
        codigoPublisherBuscado, 
        nombreOriginal, 
        g
    ); 
    
    if (ok) {
        JOptionPane.showMessageDialog(this, "Genero actualizado correctamente.");
        // Limpiar estado
        btnActualizar.setEnabled(false);
        codigoPublisherBuscado = -1;
        nombreOriginal = null;
        // Limpiar campos de texto
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
        jTextField5.setText("");
    } else {
        JOptionPane.showMessageDialog(this, "No se pudo actualizar el Genero. Publisher o Genero no encontrado.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnActualizarActionPerformed


