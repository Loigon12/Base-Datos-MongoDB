    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // 1. Obtener el ID del Publisher
    String codigoPubStr = jTextField1.getText().trim();
    
    // 2. 🚨 CRÍTICO: El servicio requiere el Nombre del Genero para encontrarlo. Lo solicitamos.
    String nombreBuscado = JOptionPane.showInputDialog(this, "Ingrese el **nombre** del Genero a buscar:");
    
    if (codigoPubStr.isEmpty() || nombreBuscado == null || nombreBuscado.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Debe ingresar el Código de Publisher y el Nombre del Genero.");
        return;
    }

    int codigoPub;
    try {
        // La variable 'texto' que usas no existe, debe ser jTextField1.getText()
        codigoPub = Integer.parseInt(codigoPubStr); 
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El Código de Publisher debe ser un número entero.");
        return;
    }

    // Resetear estado
    codigoPublisherBuscado = -1; 
    nombreOriginal = null;
    btnActualizar.setEnabled(false);

    // 3. 🚨 CRÍTICO: Llamar al servicio corregido
    Genero generoEncontrado = ServiciosGenero.buscarGeneroPorNombre(codigoPub, nombreBuscado); 

    if (generoEncontrado == null) {
        JOptionPane.showMessageDialog(this, "Genero no encontrado en el Publisher especificado.", "No encontrado", JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    // 4. ✅ GUARDAR ESTADO para la actualización
    codigoPublisherBuscado = generoEncontrado.getCodigoPublisher(); 
    nombreOriginal = generoEncontrado.getNombre(); // Guardamos el nombre original para el filtro
    btnActualizar.setEnabled(true);

    // 5. LLENAR CAMPOS con datos
    jTextField2.setText(String.valueOf(generoEncontrado.getIdGenero()));
    jTextField3.setText(generoEncontrado.getNombre());
    jTextField4.setText(String.valueOf(generoEncontrado.getCalificacion()));
    // Usamos g.getCodigoPublisher(), asumiendo que el POJO está corregido
    jTextField5.setText(String.valueOf(generoEncontrado.getCodigoPublisher())); 

    JOptionPane.showMessageDialog(this, "Genero encontrado con éxito. Ya puede actualizar los campos Nombre y Calificación.");
    }//GEN-LAST:event_btnBuscarActionPerformed

