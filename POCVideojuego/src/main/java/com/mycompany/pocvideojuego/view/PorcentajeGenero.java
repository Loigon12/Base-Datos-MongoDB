    /**
     * Muestra en lblSumatoria la sumatoria total de precios (todos los
     * registros).
     */
    private void cargarSumatoria() {
        List<Venta> ventas = ServiciosVenta.listarVentas();
        double total = ventas.stream()
                .mapToDouble(Venta::getTotalVenta)
                .sum();

        lblSumatoria.setText(String.format("Sumatoria total de ventas: $%.2f", total));
    }

    /**
     * Calcula y muestra los registros con precio > límite ingresado por el
     * usuario. Actualiza tablaResultados y lblInfo; además indica si >=50%
     * supera el límite.
     */
    private void calcularPorLimite() {
        String texto = txtLimite.getText().trim();
        if (texto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingresa un monto límite.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }

        double limite;
        try {
            limite = Double.parseDouble(texto);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Monto inválido. Ingresa un número válido.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // ✅ Obtener todas las ventas
        List<Venta> lista = ServiciosVenta.listarVentas();
        if (lista.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No hay ventas registradas.", "Información", JOptionPane.INFORMATION_MESSAGE);
            lblInfo.setText("0 ventas con monto > $" + limite);
            tablaResultados.setModel(new DefaultTableModel(new Object[]{"Código", "Cliente", "Monto", "Fecha"}, 0));
            return;
        }

        // Modelo de tabla
        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{"Código", "Cliente", "Monto", "Fecha"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        // Filtrar y contar
        long contador = 0;
        for (Venta v : lista) {
            if (v.getTotalVenta() > limite) {
                contador++;
                String fechaStr = (v.getFecha() != null)
                        ? new java.text.SimpleDateFormat("dd/MM/yyyy").format(v.getFecha())
                        : "N/A";

                modelo.addRow(new Object[]{
                    v.getCodigoVenta(),
                    v.getCliente(),
                    String.format("$%.2f", v.getTotalVenta()),
                    fechaStr
                });
            }
        }

        tablaResultados.setModel(modelo);

        // Mostrar resumen
        lblInfo.setText(String.format(
                "%d de %d ventas tienen monto > $%.2f",
                contador, lista.size(), limite
        ));

        // ✅ Calcular si ≥50% superan el límite (lógica en GUI)
        boolean mas50 = (contador * 100.0 / lista.size()) >= 50.0;
        String mensaje = mas50
                ? "El 50% o más (" + contador + " de " + lista.size() + ") superan el monto límite."
                : "Menos del 50% (" + contador + " de " + lista.size() + ") superan el monto límite.";

        JOptionPane.showMessageDialog(this, mensaje, "Análisis de ventas",
                mas50 ? JOptionPane.INFORMATION_MESSAGE : JOptionPane.WARNING_MESSAGE);
    }

