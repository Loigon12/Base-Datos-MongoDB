    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        // 🔹 Obtener valores (aunque los JTextField tengan nombres viejos, los comentamos para claridad)
    String idGeneroStr = txtIdGenero.getText().trim();
    String nombreGenero = txtNombre.getText().trim();
    String califStr = txtCalificación.getText().trim();
    String codPubStr = txtCodigoPublisher.getText().trim(); 

    // 2. Validación de campos obligatorios
    if (idGeneroStr.isEmpty() || nombreGenero.isEmpty() || califStr.isEmpty() || codPubStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios...", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 3. Conversión segura y validación de tipos
    int idGenero, calificacion, codigoPublisher;

    try {
        idGenero = Integer.parseInt(idGeneroStr);
        if (idGenero <= 0) throw new NumberFormatException();
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El ID del género debe ser un número entero positivo.", "ID inválido", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        calificacion = Integer.parseInt(califStr);
        if (calificacion < 1 || calificacion > 10) {
            JOptionPane.showMessageDialog(this, "La calificación debe estar entre 1 y 10.", "Rango no válido", JOptionPane.WARNING_MESSAGE);
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "La calificación debe ser un número entero...", "Calificación inválida", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        codigoPublisher = Integer.parseInt(codPubStr);
        if (codigoPublisher <= 0) throw new NumberFormatException();
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El código del Publisher debe ser un número entero positivo.", "Publisher inválido", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 4. Crear objeto Género
    Genero genero = new Genero();
    genero.setIdGenero(idGenero);
    genero.setNombre(nombreGenero);
    genero.setCalificacion(calificacion);
    // Note que CodigoPub (de Publisher) no es asignado al Genero, se usa para el servicio

    // 5. Guardar en MongoDB (embebido en Publisher)
    boolean exito = ServiciosGenero.agregarGenero(codigoPublisher, genero);

    // 6. Respuesta al Usuario
    if (exito) {
        JOptionPane.showMessageDialog(this, 
            String.format("✅ ¡Género '%s' (ID: %d) adicionado al Publisher %d!", nombreGenero, idGenero, codigoPublisher), 
            "Éxito", JOptionPane.INFORMATION_MESSAGE);
        
        // Limpiar campos
        txtIdGenero.setText("");
        txtNombre.setText("");
        txtCalificación.setText("");
        txtCodigoPublisher.setText("");
        txtIdGenero.requestFocus();
    } else {
        JOptionPane.showMessageDialog(this, "❌ No se pudo agregar el género. Verifica que el Publisher exista...", "Error de persistencia", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnAdicionarActionPerformed

