    private void cargarDatos() {
    DefaultTableModel modelo = new DefaultTableModel(
        new Object[]{"Código", "Nombre", "Región", "Precio Suscripción"}, 0
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    tablaPublisher.setModel(modelo);

    try {
        tablaPublisher.getColumnModel().getColumn(4).setMaxWidth(140); // Acciones
    } catch (Exception ex) {
        // ignore
    }

    List<Publisher> lista = ServiciosPublisher.listarPublisher();
    for (Publisher pb : lista) {
        String regionMostrar = (pb.getRegion() == null || pb.getRegion().trim().isEmpty()) ? "Desconocida" : pb.getRegion();
        modelo.addRow(new Object[]{
            pb.getCodigoPublisher(),
            pb.getNombre(),
            regionMostrar,
            pb.getPrecioSuscripcion(),
        });
    }
}

    private void editarPublisher(int fila) {
        if (fila < 0) return;

        DefaultTableModel modelo = (DefaultTableModel) tablaPublisher.getModel();
        Object oCodigo = modelo.getValueAt(fila, 0);
        int codigoPublisher;
        try {
            if (oCodigo instanceof Integer) codigoPublisher = (Integer) oCodigo;
            else codigoPublisher = Integer.parseInt(oCodigo.toString().trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Código de publisher inválido.");
            return;
        }

        Publisher pb = ServiciosPublisher.buscarPublisher(codigoPublisher);
        if (pb == null) {
            JOptionPane.showMessageDialog(this, "No se encontró el publisher seleccionado.");
            return;
        }

        // Pedimos nuevos valores
        String nuevoNombre = JOptionPane.showInputDialog(this, "Nombre:", pb.getNombre());
        if (nuevoNombre == null) return;

        String nuevaRegion = JOptionPane.showInputDialog(this, "Región:", pb.getRegion());
        if (nuevaRegion == null) return;

        String precioStr = JOptionPane.showInputDialog(this, "Precio Suscripción:", String.valueOf(pb.getPrecioSuscripcion()));
        if (precioStr == null) return;
        double nuevoPrecio;
        try {
            nuevoPrecio = Double.parseDouble(precioStr.trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Precio inválido. Operación cancelada.");
            return;
        }

        // Actualizamos el objeto
        pb.setNombre(nuevoNombre.trim());
        pb.setRegion(nuevaRegion.trim());
        pb.setPrecioSuscripcion(nuevoPrecio);

        boolean ok = ServiciosPublisher.actualizarPublisher(pb);
        if (ok) {
            JOptionPane.showMessageDialog(this, "Publisher actualizado.");
            cargarDatos();
        } else {
            JOptionPane.showMessageDialog(this, "Error al actualizar.");
        }
    }


