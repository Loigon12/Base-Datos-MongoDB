    private void btnEliminar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminar1ActionPerformed
              int fila = tablaPublisher.getSelectedRow();
    if (fila < 0) {
        JOptionPane.showMessageDialog(this, "Selecciona un registro para eliminar.");
        return;
    }

    DefaultTableModel modelo = (DefaultTableModel) tablaPublisher.getModel();
    Object oCodigo = modelo.getValueAt(fila, 0);
    int codigoPublisher;
    try {
        if (oCodigo instanceof Integer) codigoPublisher = (Integer) oCodigo;
        else codigoPublisher = Integer.parseInt(oCodigo.toString().trim());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Código de publisher inválido.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(this, 
        "¿Estás seguro de eliminar este Publisher?", 
        "Confirmar eliminación", JOptionPane.YES_NO_OPTION);

    if (confirm == JOptionPane.YES_OPTION) {
        boolean ok = ServiciosPublisher.eliminarPublisher(codigoPublisher);
        if (ok) {
            JOptionPane.showMessageDialog(this, "Publisher eliminado.");
            cargarDatos(); // recarga la tabla
        } else {
            JOptionPane.showMessageDialog(this, "Error al eliminar el Publisher.");
        }
    }
    }//GEN-LAST:event_btnEliminar1ActionPerformed

