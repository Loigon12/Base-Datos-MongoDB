    private void btnEliminarVActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarVActionPerformed
        int fila = tablaVenta.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Selecciona un registro para eliminar.");
            return;
        }

        DefaultTableModel modelo = (DefaultTableModel) tablaVenta.getModel();
        Object oCodigo = modelo.getValueAt(fila, 0);
        int codigoVenta;
        try {
            if (oCodigo instanceof Integer) codigoVenta = (Integer) oCodigo;
            else codigoVenta = Integer.parseInt(oCodigo.toString().trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Código de Venta inválido.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
            "¿Estás seguro de eliminar esta Venta?",
            "Confirmar eliminación", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            boolean ok = ServiciosVenta.eliminarVenta(codigoVenta);
            if (ok) {
                JOptionPane.showMessageDialog(this, "Venta eliminada.");
                cargarDatos(); // recarga la tabla
            } else {
                JOptionPane.showMessageDialog(this, "Error al eliminar la tabla.");
            }
        }
    }//GEN-LAST:event_btnEliminarVActionPerformed

