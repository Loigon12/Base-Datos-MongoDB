    /**
     * Prepara el modelo de la tabla para asegurar que las columnas sean correctas.
     */
    private void iniciarTablaVenta() {
        String[] columnas = {"Código Venta", "Cliente", "Fecha", "Total Venta"};
        // Creamos un modelo de tabla vacío con las columnas definidas
        DefaultTableModel modelo = new DefaultTableModel(null, columnas);
        tablaVenta.setModel(modelo);
    }
    
    /**
     * Carga todos los datos de ventas desde el servicio (ServiciosVenta) a la tabla.
     */
    public void cargarDatos() {
        // 1. Obtiene el modelo de la tabla
        DefaultTableModel modelo = (DefaultTableModel) tablaVenta.getModel();
        
        // 2. Limpia las filas existentes antes de cargar las nuevas
        modelo.setRowCount(0);
        
        try {
            // 3. Obtiene la lista de ventas
            List<Venta> ventas = ServiciosVenta.listarVentas();
            
            // 4. Itera la lista y añade cada venta como una fila
            for (Venta venta : ventas) {
                Object[] fila = new Object[4];
                // ----------------------------------------------------
                //  ¡ESTAS SON LAS LÍNEAS A CAMBIAR!
                // ----------------------------------------------------
                fila[0] = venta.getCodigoVenta(); // ✅ Usar getCodigoVenta()
                fila[1] = venta.getCliente(); // ✅ Usar getCliente()
                fila[2] = venta.getFecha(); // ✅ Correcto: getFecha()
                fila[3] = venta.getTotalVenta(); // ✅ Usar getTotalVenta()
                
                modelo.addRow(fila);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar las ventas: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

   

