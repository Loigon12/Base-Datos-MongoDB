    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        // Obtener valores de los campos
         String codigoStr = txtCodigoPublisher.getText().trim();
    String nombre = txtNombre.getText().trim();
    String precioStr = txtPrecioSuscripcion.getText().trim();
    String region = txtregion.getText().trim();

    if (codigoStr.isEmpty() || nombre.isEmpty() || precioStr.isEmpty() || region.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.");
        return;
    }

    int codigoPublisher;
    double precioSuscripcion;
    
    try {
        codigoPublisher = Integer.parseInt(codigoStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El código de publisher debe ser un número entero.");
        return;
    }

    try {
        precioSuscripcion = Double.parseDouble(precioStr);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El precio de suscripción debe ser un número válido.");
        return;
    }

    // ✅ Crear Publisher sin id (MongoDB lo generará)
    Publisher pub = new Publisher(codigoPublisher, nombre, region, precioSuscripcion, "si");

    // ✅ Guardar
    boolean respuesta = ServiciosPublisher.agregarPublisher(pub); // 👈 usa agregarPublisher

    if (respuesta) {
        JOptionPane.showMessageDialog(this, "¡Publisher adicionado con éxito!");
        txtCodigoPublisher.setText("");
        txtNombre.setText(""); 
        txtPrecioSuscripcion.setText("");
        txtregion.setText("");
    } else {
        JOptionPane.showMessageDialog(this, "Error al adicionar el Publisher.");
    }
    }//GEN-LAST:event_btnAdicionarActionPerformed

