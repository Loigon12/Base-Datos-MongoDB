    /**
     * Carga los videojuegos desde el servicio y los muestra en la tabla.
     */
    private void cargarDatos() {
        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{"Código", "Nombre", "Precio", "Estado", "Codigo Publisher", "Publisher", "Acciones"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        tablaVideojuegos.setModel(modelo);

        try {
            tablaVideojuegos.getColumnModel().getColumn(6).setMaxWidth(140); // Acciones
        } catch (Exception ex) {
            // ignore
        }

        List<Videojuego> lista = ServiciosVideojuego.listarVideojuegos();
        for (Videojuego v : lista) {
            String estadoMostrar = (v.getEstado() == null || v.getEstado().trim().isEmpty())
                    ? "Disponible" : v.getEstado();

            // ?Buscar el nombre del publisher (solo para mostrar)
            Publisher pb = ServiciosPublisher.buscarPublisher(v.getCodigoPublisher());
            String nombrePublisher = (pb != null) ? pb.getNombre() : "Desconocido";
            // Usamos v.getCodigoPublisher() directamente — no depende de pb
            int codigoPublisher = v.getCodigoPublisher();

            modelo.addRow(new Object[]{
                v.getCodigoSerie(),
                v.getNombre(),
                v.getPrecio(),
                estadoMostrar,
                codigoPublisher, // ← ¡seguro!
                nombrePublisher, // ← puede ser "Desconocido"
                "Editar/Alternar"
            });
        }}
        /**
         * Edita un videojuego seleccionado (no permite cambiar estado aquí).
         * Pedimos nuevo nombre y precio (estado NO editable desde aquí).
         */
    private void editarVideojuego(int fila) {
        if (fila < 0) {
            return;
        }

        DefaultTableModel modelo = (DefaultTableModel) tablaVideojuegos.getModel();
        Object oCodigo = modelo.getValueAt(fila, 0);
        int codigoSerie;
        try {
            if (oCodigo instanceof Integer) {
                codigoSerie = (Integer) oCodigo;
            } else {
                codigoSerie = Integer.parseInt(oCodigo.toString().trim());
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Código de serie inválido.");
            return;
        }

        Videojuego v = ServiciosVideojuego.buscarVideojuego(codigoSerie);
        if (v == null) {
            JOptionPane.showMessageDialog(this, "No se encontró el videojuego seleccionado.");
            return;
        }

        // Pedimos nuevos valores (estado no se pide)
        String nuevoNombre = JOptionPane.showInputDialog(this, "Nombre:", v.getNombre());
        if (nuevoNombre == null) {
            return; // cancelado
        }
        String precioStr = JOptionPane.showInputDialog(this, "Precio:", String.valueOf(v.getPrecio()));
        if (precioStr == null) {
            return;
        }
        double nuevoPrecio;
        try {
            nuevoPrecio = Double.parseDouble(precioStr.trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Precio inválido. Operación cancelada.");
            return;
        }

        // Actualizamos el objeto (solo nombre/precio)
        v.setNombre(nuevoNombre.trim());
        v.setPrecio(nuevoPrecio);

        boolean ok = ServiciosVideojuego.actualizarVideojuego(v);
        if (ok) {
            JOptionPane.showMessageDialog(this, "Videojuego actualizado.");
            cargarDatos();
        } else {
            JOptionPane.showMessageDialog(this, "Error al actualizar.");
        }
    }

    /**
     * Alterna el estado del videojuego entre Disponible o No disponible y
     * guarda el cambio.
     */
    private void alternarEstado(int fila) {
        if (fila < 0) {
            return;
        }

        DefaultTableModel modelo = (DefaultTableModel) tablaVideojuegos.getModel();
        Object oCodigo = modelo.getValueAt(fila, 0);
        int codigoSerie;
        try {
            if (oCodigo instanceof Integer) {
                codigoSerie = (Integer) oCodigo;
            } else {
                codigoSerie = Integer.parseInt(oCodigo.toString().trim());
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Código de serie inválido.");
            return;
        }

        Videojuego v = ServiciosVideojuego.buscarVideojuego(codigoSerie);
        if (v == null) {
            JOptionPane.showMessageDialog(this, "No se encontró el videojuego seleccionado.");
            return;
        }

        String actual = v.getEstado();
        String nuevo;
        if (actual == null || actual.trim().isEmpty() || actual.equalsIgnoreCase("Disponible")) {
            nuevo = "No disponible";
        } else {
            nuevo = "Disponible";
        }
        v.setEstado(nuevo);

        boolean ok = ServiciosVideojuego.actualizarVideojuego(v);
        if (ok) {
            JOptionPane.showMessageDialog(this, "Estado cambiado a: " + nuevo);
            cargarDatos();
        } else {
            JOptionPane.showMessageDialog(this, "Error al cambiar el estado.");
        }
    }

