    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tablaVideojuegos.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Selecciona un registro para eliminar.");
            return;
        }

        DefaultTableModel modelo = (DefaultTableModel) tablaVideojuegos.getModel();
        Object oCodigo = modelo.getValueAt(fila, 0);
        int codigoSerie;
        try {
            if (oCodigo instanceof Integer) {
                codigoSerie = (Integer) oCodigo;
            } else {
                codigoSerie = Integer.parseInt(oCodigo.toString().trim());
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Código de serie inválido.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "¿Estás seguro de eliminar este videojuego?",
                "Confirmar eliminación", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            boolean ok = ServiciosVideojuego.eliminarVideojuego(codigoSerie);
            if (ok) {
                JOptionPane.showMessageDialog(this, "Videojuego eliminado.");
                cargarDatos(); // recarga la tabla
            } else {
                JOptionPane.showMessageDialog(this, "Error al eliminar el videojuego.");
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

