    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        String codigoStr = jTextField2.getText().trim();
        if (codigoStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No hay código de Venta para actualizar. Realiza la búsqueda primero.");
            return;
        }

        int codigoVenta;
        try {
            codigoVenta = Integer.parseInt(codigoStr); 
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Código de Venta inválido.");
            return;
        }

        // 1. Buscar la Venta existente para actualizar
        Venta v = ServiciosVenta.buscarVenta(codigoVenta);
        if (v == null) {
            JOptionPane.showMessageDialog(this, "No se encontró la Venta para actualizar.");
            return;
        }

        // 2. Obtener y actualizar el Cliente
        String cliente = jTextField3.getText().trim();
        if (!cliente.isEmpty()) {
            v.setCliente(cliente); 
        }

        // 3. Obtener y actualizar la Fecha (Manejo de parseo de Date)
        String fechaStr = jTextField4.getText().trim();
        if (!fechaStr.isEmpty()) {
            try {
                // El formato debe coincidir con el mostrado en la búsqueda (YYYY-MM-DD)
                SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
                Date fecha = sdf.parse(fechaStr);
                v.setFecha(fecha); 
            } catch (java.text.ParseException ex) {
                JOptionPane.showMessageDialog(this, "Formato de fecha inválido (debe ser YYYY-MM-DD). La fecha no se actualizará.");
                return; 
            }
        }

        // 4. Obtener y actualizar el Total de Venta
        String totalStr = jTextField5.getText().trim();
        if (!totalStr.isEmpty()) {
            totalStr = totalStr.replace("$", "").replace(",", ".").trim();
            try {
                double total = Double.parseDouble(totalStr);
                v.setTotalVenta(total); 
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Total de Venta inválido (debe ser un número).");
                return;
            }
        }
        
        // 5. Llamar al servicio de actualización
        boolean ok = ServiciosVenta.actualizarVenta(v);
        if (ok) {
            JOptionPane.showMessageDialog(this, "Venta actualizada correctamente.");
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo actualizar la Venta. Verifica los datos.");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed


