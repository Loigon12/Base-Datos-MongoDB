    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String texto = jTextField1.getText().trim();

        if (texto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingresa el código de venta para buscar.");
            return;
        }

        Venta ventaEncontrada = null;
        int codigo;

        // Intentar buscar SOLO por código de venta (entero)
        try {
            codigo = Integer.parseInt(texto);
            ventaEncontrada = ServiciosVenta.buscarVenta(codigo);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Búsqueda solo por código. Por favor, ingresa un número válido.");
            jTextField1.setText(""); 
            return;
        }

        if (ventaEncontrada == null) {
            JOptionPane.showMessageDialog(this, "No se encontró ninguna venta con ese código.");

            // Limpiar los campos si no se encuentra nada
            jTextField2.setText("");
            jTextField3.setText("");
            jTextField4.setText("");
            jTextField5.setText("");
            return;
        }

        // Formato para mostrar la fecha (YYYY-MM-DD)
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

        // ✅ Mostrar información de VENTA (usando los métodos correctos de Venta)
        jTextField2.setText(String.valueOf(ventaEncontrada.getCodigoVenta())); // Código
        jTextField3.setText(ventaEncontrada.getCliente());                   // Cliente
        jTextField4.setText(sdf.format(ventaEncontrada.getFecha()));         // Fecha
        jTextField5.setText(String.format("%.2f", ventaEncontrada.getTotalVenta())); // Total

        JOptionPane.showMessageDialog(this, "Venta encontrada con éxito. Puedes editar los campos y actualizar.");
    
    }//GEN-LAST:event_btnBuscarActionPerformed

