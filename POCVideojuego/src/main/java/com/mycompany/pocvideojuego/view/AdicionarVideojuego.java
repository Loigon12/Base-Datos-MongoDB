    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
    // Obtener valores de los campos
    String codigoStr = txtCodigoSerie.getText().trim();
    String nombre = txtNombre.getText().trim();
    String precioStr = txtPrecio.getText().trim();
    String codigoPbStr = txtCodigoPublisher.getText().trim();
    String codigoVtStr = txtCodigoVenta.getText().trim(); // ← nuevo campo

    // Validaciones básicas (código, nombre, precio, publisher son obligatorios)
    if (codigoStr.isEmpty() || nombre.isEmpty() || precioStr.isEmpty() || codigoPbStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, 
            "Campos obligatorios:\n• Código Serie\n• Nombre\n• Precio\n• Código Publisher",
            "Campos incompletos", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int codigoSerie, codigoPublisher, codigoVenta = 0; // por defecto: sin venta
    double precio;

    // Validar código de serie
    try {
        codigoSerie = Integer.parseInt(codigoStr);
        if (codigoSerie <= 0) throw new NumberFormatException();
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El código de serie debe ser un entero positivo.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Validar precio
    try {
        precio = Double.parseDouble(precioStr);
        if (precio < 0) {
            JOptionPane.showMessageDialog(this, "El precio no puede ser negativo.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El precio debe ser un número válido (ej. 59.99).", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Validar código de publisher
    try {
        codigoPublisher = Integer.parseInt(codigoPbStr);
        if (codigoPublisher <= 0) throw new NumberFormatException();
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El código de publisher debe ser un entero positivo.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Validar código de venta (opcional: puede estar vacío)
    if (!codigoVtStr.isEmpty()) {
        try {
            codigoVenta = Integer.parseInt(codigoVtStr);
            if (codigoVenta <= 0) {
                JOptionPane.showMessageDialog(this, "El código de venta debe ser positivo o dejar en blanco.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El código de venta debe ser un número entero válido.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
    } // Si está vacío, se mantiene codigoVenta = 0 (sin venta)

    // Crear objeto Videojuego
    Videojuego videojuego = new Videojuego();
    videojuego.setCodigoSerie(codigoSerie);
    videojuego.setNombre(nombre);
    videojuego.setEstado("Disponible");        // Estado inicial
    videojuego.setEntregado(false);            // Por defecto no entregado
    videojuego.setPrecio(precio);
    videojuego.setCodigoPublisher(codigoPublisher);
    videojuego.setCodigoVenta(codigoVenta);    // ← ¡asignamos la referencia!

    // Guardar usando el servicio
    boolean respuesta = ServiciosVideojuego.agregarVideojuego(videojuego);

    if (respuesta) {
        String msg = String.format("Videojuego '%s' (ID: %d) adicionado con éxito.", nombre, codigoSerie);
        if (codigoVenta > 0) {
            msg += String.format("\n→ Asignado a Venta #%d", codigoVenta);
        }
        JOptionPane.showMessageDialog(this, msg, "Éxito", JOptionPane.INFORMATION_MESSAGE);

        // Limpiar todos los campos
        txtCodigoSerie.setText("");
        txtNombre.setText("");
        txtPrecio.setText("");
        txtCodigoPublisher.setText("");
        txtCodigoVenta.setText(""); // ← limpiar también
        txtCodigoSerie.requestFocus(); // enfocar en primer campo

    } else {
        String msg = "No se pudo agregar el videojuego.\n";
        msg += "• ¿Ya existe uno con ese código?\n";
        msg += "• ¿El Publisher #" + codigoPublisher + " existe?\n";
        if (codigoVenta > 0) {
            msg += "• ¿La Venta #" + codigoVenta + " existe?\n";
        }
        msg += "• ¿MongoDB está ejecutándose? (localhost:27017)";
        
        JOptionPane.showMessageDialog(this, msg, "Error de persistencia", JOptionPane.ERROR_MESSAGE);
        
        System.err.println("Falló agregarVideojuego(" + codigoSerie + ", " + nombre + ")");
    }
    }//GEN-LAST:event_btnAdicionarActionPerformed


