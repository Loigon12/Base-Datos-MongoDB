public final void cargarDatos() {
    DefaultTableModel modelo = (DefaultTableModel) tablaGenero.getModel();
    modelo.setRowCount(0); // Limpiar datos existentes

    List<Genero> generos = ServiciosGenero.listarGenero();
    
    for (Genero g : generos) {
        modelo.addRow(new Object[]{
            g.getIdGenero(),
            g.getNombre(),
            g.getCalificacion(),
            // ❌ CORRECCIÓN: Cambiar g.getCodigoPub() por g.getCodigoPublisher()
            g.getCodigoPublisher() 
        });
    }
}

