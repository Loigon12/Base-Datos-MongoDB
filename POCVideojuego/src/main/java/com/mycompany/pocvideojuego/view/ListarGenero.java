    private void btnEliminarVActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarVActionPerformed
     int fila = tablaGenero.getSelectedRow();
    if (fila < 0) {
        JOptionPane.showMessageDialog(this, "Selecciona un género para eliminar.");
        return;
    }

    DefaultTableModel modelo = (DefaultTableModel) tablaGenero.getModel();
    
    // 1. Obtener datos de la fila seleccionada
    String nombreGenero = modelo.getValueAt(fila, 1).toString().trim();
    Object oCodPub = modelo.getValueAt(fila, 3);
    
    int codigoPublisher;
    try {
        codigoPublisher = Integer.parseInt(oCodPub.toString().trim());
        if (codigoPublisher <= 0) throw new NumberFormatException();
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Código de Publisher inválido en la fila seleccionada.");
        return;
    }

    // 2. Confirmar
    int confirm = JOptionPane.showConfirmDialog(this,
        String.format("¿Eliminar el género '%s' del Publisher %d?", nombreGenero, codigoPublisher),
        "Confirmar eliminación", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
    
    if (confirm != JOptionPane.YES_OPTION) return;

    // 3. Ejecutar eliminación
    boolean ok = ServiciosGenero.eliminarGenero(codigoPublisher, nombreGenero);
    
    if (ok) {
        JOptionPane.showMessageDialog(this, "✅ Género eliminado con éxito.");
        cargarDatos(); // ✅ Refresca la tabla
    } else {
        JOptionPane.showMessageDialog(this, "❌ No se pudo eliminar el género.\n"
            + "Verifica que exista y que el Publisher esté activo.");
    }
    }//GEN-LAST:event_btnEliminarVActionPerformed

